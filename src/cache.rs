use crate::config::{cache_path, Config};
use crate::providers;
use sha2::{Digest, Sha256};
use std::fs;
use std::path::Path;
use std::process::Command;
use thiserror::Error;

#[derive(Error, Debug)]
pub enum CacheError {
    #[error("failed to write cache: {0}")]
    WriteError(#[from] std::io::Error),
    #[error("generated cache has invalid shell syntax")]
    InvalidSyntax,
}

/// Generate the shell cache script from config.
pub fn generate_cache(config: &Config) -> String {
    let mut out = String::new();
    let config_yaml = serde_yaml::to_string(config).unwrap_or_default();
    let hash = config_hash(&config_yaml);

    out.push_str(&format!(
        "# Generated by aitch — do not edit\n# Config hash: {}\n\n",
        hash
    ));

    out.push_str("_aitch_resolve() {\n");

    // Priority 1: .aitch file walk-up
    out.push_str("  # Priority 1: .aitch file\n");
    out.push_str("  local _d=\"$PWD\"\n");
    out.push_str("  while [ \"$_d\" != '/' ]; do\n");
    out.push_str("    if [ -f \"$_d/.aitch\" ]; then\n");
    out.push_str("      local _p\n");
    out.push_str("      _p=$(cat \"$_d/.aitch\" 2>/dev/null | tr -d '[:space:]')\n");
    out.push_str("      case \"$_p\" in\n");
    for (name, profile) in &config.profiles {
        out.push_str(&format!("        '{}')\n", shell_escape(name)));
        out.push_str(&env_exports(profile));
        out.push_str("          return 0\n");
        out.push_str("          ;;\n");
    }
    out.push_str("      esac\n");
    out.push_str("    fi\n");
    out.push_str("    _d=$(dirname \"$_d\")\n");
    out.push_str("  done\n\n");

    // Priority 2: Directory prefix match (case-insensitive for macOS)
    out.push_str("  # Priority 2: Directory prefix match\n");
    out.push_str("  local _pwd_lower\n");
    out.push_str("  _pwd_lower=$(printf '%s' \"$PWD\" | tr '[:upper:]' '[:lower:]')\n");
    out.push_str("  case \"$_pwd_lower\" in\n");
    for (name, profile) in &config.profiles {
        let patterns: Vec<String> = profile
            .directories
            .iter()
            .map(|d| {
                // The folder itself or anything inside it, never a sibling sharing the prefix.
                let dir = shell_escape(&expand_tilde(d).trim_end_matches('/').to_lowercase());
                format!("'{dir}'|'{dir}'/*")
            })
            .collect();
        if !patterns.is_empty() {
            out.push_str(&format!(
                "    {})\n",
                patterns.join("|")
            ));
            out.push_str(&env_exports(profile));
            out.push_str("      return 0\n");
            out.push_str("      ;;\n");
        }
        let _ = name; // used above in .aitch section
    }
    out.push_str("  esac\n\n");

    // Priority 3: Git remote match
    out.push_str("  # Priority 3: Git remote match\n");
    out.push_str("  local _remote\n");
    out.push_str("  _remote=$(git remote get-url origin 2>/dev/null) || true\n");
    out.push_str("  if [ -n \"$_remote\" ]; then\n");
    out.push_str("    case \"$_remote\" in\n");
    for (_name, profile) in &config.profiles {
        let patterns: Vec<String> = profile
            .git_remotes
            .iter()
            .map(|r| {
                if let Some(prefix) = r.strip_suffix('*') {
                    format!("*'{}'*", shell_escape(prefix))
                } else {
                    format!("*'{}'*", shell_escape(r))
                }
            })
            .collect();
        if !patterns.is_empty() {
            out.push_str(&format!("      {})\n", patterns.join("|")));
            out.push_str(&env_exports(profile));
            out.push_str("        return 0\n");
            out.push_str("        ;;\n");
        }
    }
    out.push_str("    esac\n");
    out.push_str("  fi\n\n");

    // Priority 4: Default profile
    if let Some(default_name) = &config.default {
        if let Some(profile) = config.profiles.get(default_name) {
            out.push_str("  # Priority 4: Default profile\n");
            out.push_str(&env_exports(profile));
        }
    }

    out.push_str("}\n\n");
    out.push_str("_aitch_resolve\n");

    out
}

/// Generate env export lines for a profile.
fn env_exports(profile: &crate::config::Profile) -> String {
    let mut out = String::new();
    for (key, value) in &profile.providers {
        if let Some(env_var) = providers::get_env_var(key) {
            // An empty value means "use the tool's default folder": remove any inherited value.
            if value.trim().is_empty() {
                out.push_str(&format!("          unset {}\n", env_var));
                continue;
            }
            let expanded = expand_tilde(value);
            out.push_str(&format!(
                "          export {}='{}'\n",
                env_var,
                shell_escape(&expanded)
            ));
        }
    }
    out
}

/// Escape a string for safe embedding in single-quoted shell context.
/// Single quotes within the string are escaped as '\'' (end quote, escaped quote, start quote).
fn shell_escape(s: &str) -> String {
    s.replace('\'', "'\\''")
}

/// Expand ~ to home directory.
fn expand_tilde(path: &str) -> String {
    if let Some(rest) = path.strip_prefix("~/") {
        if let Some(home) = dirs::home_dir() {
            return home.join(rest).to_string_lossy().to_string();
        }
    }
    path.to_string()
}

/// Compute a short hash of the config content for staleness detection.
fn config_hash(content: &str) -> String {
    let mut hasher = Sha256::new();
    hasher.update(content.as_bytes());
    let result = hasher.finalize();
    hex::encode(&result[..8])
}

/// Write the cache file atomically: write to tmp, validate syntax, then rename.
pub fn write_cache(config: &Config) -> Result<(), CacheError> {
    write_cache_to(config, &cache_path())
}

pub fn write_cache_to(config: &Config, path: &Path) -> Result<(), CacheError> {
    let content = generate_cache(config);
    let tmp_path = path.with_extension("tmp");

    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }

    fs::write(&tmp_path, &content)?;

    // Validate shell syntax
    let status = Command::new("sh")
        .arg("-n")
        .arg(&tmp_path)
        .status();

    match status {
        Ok(s) if s.success() => {
            fs::rename(&tmp_path, path)?;
            Ok(())
        }
        _ => {
            let _ = fs::remove_file(&tmp_path);
            Err(CacheError::InvalidSyntax)
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::{Config, Profile};
    use std::collections::BTreeMap;
    use tempfile::TempDir;

    fn test_config() -> Config {
        let mut profiles = BTreeMap::new();

        let mut work = Profile::default();
        work.providers
            .insert("claude".to_string(), "/tmp/claude-work".to_string());
        work.directories.push("/tmp/projects/acme".to_string());
        work.git_remotes.push("github.com/acme/*".to_string());

        let mut personal = Profile::default();
        personal
            .providers
            .insert("claude".to_string(), "/tmp/claude-personal".to_string());
        personal
            .directories
            .push("/tmp/projects/personal".to_string());

        profiles.insert("work".to_string(), work);
        profiles.insert("personal".to_string(), personal);

        Config {
            default: Some("personal".to_string()),
            profiles,
        }
    }

    #[test]
    fn generate_cache_produces_valid_shell() {
        let config = test_config();
        let cache = generate_cache(&config);
        assert!(cache.contains("_aitch_resolve"));
        assert!(cache.contains("CLAUDE_CONFIG_DIR"));
        assert!(cache.contains("/tmp/projects/acme"));
        // Verify case-insensitive matching: PWD is lowered before case match
        assert!(cache.contains("_pwd_lower"));
        assert!(cache.contains("tr '[:upper:]' '[:lower:]'"));
    }

    /// Source the generated cache in bash from `dir` with CLAUDE_CONFIG_DIR preset to "PRESET";
    /// return what the variable ends up as ("UNSET" when unset).
    fn run_cache(cache: &str, dir: &std::path::Path) -> String {
        let tmp = tempfile::NamedTempFile::new().unwrap();
        std::fs::write(tmp.path(), cache).unwrap();
        let out = Command::new("bash")
            .arg("-c")
            .arg(format!(
                "cd '{}' && export CLAUDE_CONFIG_DIR=PRESET && source '{}' && printf '%s' \"${{CLAUDE_CONFIG_DIR-UNSET}}\"",
                dir.display(),
                tmp.path().display()
            ))
            .output()
            .unwrap();
        assert!(out.status.success(), "{}", String::from_utf8_lossy(&out.stderr));
        String::from_utf8_lossy(&out.stdout).to_string()
    }

    fn boundary_config(root: &std::path::Path, personal_claude: &str) -> Config {
        let mut profiles = BTreeMap::new();
        let mut work = Profile::default();
        work.providers.insert("claude".to_string(), "/tmp/claude-work".to_string());
        work.directories.push(root.join("acme").to_string_lossy().to_string());
        let mut personal = Profile::default();
        personal.providers.insert("claude".to_string(), personal_claude.to_string());
        profiles.insert("work".to_string(), work);
        profiles.insert("personal".to_string(), personal);
        Config { default: Some("personal".to_string()), profiles }
    }

    #[test]
    fn cache_directory_match_stops_at_a_folder_boundary() {
        let root = tempfile::TempDir::new().unwrap();
        for d in ["acme/svc", "acme-ideas"] {
            std::fs::create_dir_all(root.path().join(d)).unwrap();
        }
        let cache = generate_cache(&boundary_config(root.path(), "/tmp/claude-personal"));
        assert_eq!(run_cache(&cache, &root.path().join("acme")), "/tmp/claude-work");
        assert_eq!(run_cache(&cache, &root.path().join("acme/svc")), "/tmp/claude-work");
        assert_eq!(run_cache(&cache, &root.path().join("acme-ideas")), "/tmp/claude-personal");
    }

    #[test]
    fn empty_provider_value_unsets_the_variable() {
        let root = tempfile::TempDir::new().unwrap();
        std::fs::create_dir_all(root.path().join("elsewhere")).unwrap();
        let cache = generate_cache(&boundary_config(root.path(), ""));
        // Default profile with an empty claude provider: the inherited value is removed, so
        // Claude Code falls back to its default folder (~/.claude).
        assert_eq!(run_cache(&cache, &root.path().join("elsewhere")), "UNSET");
    }

    #[test]
    fn generate_cache_empty_config() {
        let config = Config::default();
        let cache = generate_cache(&config);
        assert!(cache.contains("_aitch_resolve"));
        // Should still be valid shell
    }

    #[test]
    fn shell_escape_handles_quotes() {
        assert_eq!(shell_escape("it's"), "it'\\''s");
        assert_eq!(shell_escape("normal"), "normal");
    }

    #[test]
    fn atomic_write_creates_cache() {
        let dir = TempDir::new().unwrap();
        let path = dir.path().join("cache");
        let config = test_config();
        write_cache_to(&config, &path).unwrap();
        assert!(path.exists());
        let content = fs::read_to_string(&path).unwrap();
        assert!(content.contains("_aitch_resolve"));
    }

    #[test]
    fn atomic_write_no_tmp_left_behind() {
        let dir = TempDir::new().unwrap();
        let path = dir.path().join("cache");
        let config = test_config();
        write_cache_to(&config, &path).unwrap();
        assert!(!path.with_extension("tmp").exists());
    }

    #[test]
    fn config_hash_is_deterministic() {
        let h1 = config_hash("test content");
        let h2 = config_hash("test content");
        assert_eq!(h1, h2);
        let h3 = config_hash("different");
        assert_ne!(h1, h3);
    }

    #[test]
    fn shell_injection_blocked_by_quoting() {
        let mut config = Config::default();
        let mut evil = Profile::default();
        // Even if validation was bypassed, quoting prevents execution
        evil.providers
            .insert("claude".to_string(), "/tmp/safe-path".to_string());
        evil.directories
            .push("/tmp/normal/path".to_string());
        config.profiles.insert("evil".to_string(), evil);

        let cache = generate_cache(&config);
        // All paths should be single-quoted in output
        assert!(cache.contains("'/tmp/safe-path'"));
        assert!(cache.contains("'/tmp/normal/path'"));
    }
}
